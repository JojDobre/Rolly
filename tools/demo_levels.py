def level(level_id, name, rows):
    width = len(rows[0])
    assert all(len(r) == width for r in rows), (name, [len(r) for r in rows])
    cells = {}
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            assert ch in LEGEND, (name, ch, x, y)
            cells[f"{x},{y}"] = dict(LEGEND[ch])
    stars = sum(r.count("*") for r in rows)
    assert stars == 3, (name, stars)
    return {"id": level_id, "name": name, "width": width, "height": len(rows), "cells": cells}


